/**
 * Получить слово дня — детерминированно по дате, одинаково для всех без сервера.
 * Seed = количество дней с эпохи Unix.
 */
export function getDailyWord(): string {
  const daysSinceEpoch = Math.floor(Date.now() / 86400000)
  const answers = VALID_ANSWERS
  return answers[daysSinceEpoch % answers.length]
}

/** Получить случайное слово */
export function getRandomWord(): string {
  const answers = VALID_ANSWERS
  return answers[Math.floor(Math.random() * answers.length)]
}

/** Проверить, есть ли слово в словаре */
